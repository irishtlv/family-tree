// Prints SQL that loads src/data/seed.json into Supabase.
// Usage: npm run seed-sql   (writes supabase/seed.sql)
import { readFileSync } from 'node:fs'

const seed = JSON.parse(readFileSync(new URL('../src/data/seed.json', import.meta.url), 'utf8'))
const q = s => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const out = ['-- generated by scripts/make-seed-sql.mjs', 'begin;']
for (const [id, p] of Object.entries(seed.people)) {
  out.push(`insert into people(id, data) values (${q(id)}, ${q(JSON.stringify(p))}::jsonb) on conflict (id) do update set data = excluded.data;`)
}
for (const u of seed.unions) {
  const kids = u.children.length ? `array[${u.children.map(q).join(',')}]` : `'{}'::text[]`
  out.push(`insert into unions(id, a, b, status, children) values (${q(u.id)}, ${q(u.a)}, ${q(u.b)}, ${q(u.status)}, ${kids}) on conflict (id) do nothing;`)
}
out.push(`insert into settings(key, value) values ('home', to_jsonb(${q(seed.home)}::text)) on conflict (key) do update set value = excluded.value;`)
out.push('commit;')
console.log(out.join('\n'))
